// 双线性采样点田强度（0–1）：入参为插画归一化坐标，格中心对齐，边缘自动收住。
export function sampleHalftoneField(u: number, v: number): number {
  const fx = Math.min(FIELD_W - 1.001, Math.max(0, u * FIELD_W - 0.5))
  const fy = Math.min(FIELD_H - 1.001, Math.max(0, v * FIELD_H - 0.5))
  const x0 = Math.floor(fx)
  const y0 = Math.floor(fy)
  const tx = fx - x0
  const ty = fy - y0
  const x1 = Math.min(FIELD_W - 1, x0 + 1)
  const y1 = Math.min(FIELD_H - 1, y0 + 1)
  const at = (x: number, y: number) =>
    parseInt(FIELD_DATA[y * FIELD_W + x] ?? '0', 16) / 15
  const top = at(x0, y0) * (1 - tx) + at(x1, y0) * tx
  const bottom = at(x0, y1) * (1 - tx) + at(x1, y1) * tx
  return top * (1 - ty) + bottom * ty
}

// 点田颜色随插画横向位置色移：左段亮青蓝、中段紫、右段品红紫，与原图蓝→紫背景渐变同系。
export function halftoneFieldColor(u: number): [number, number, number] {
  const stops: Array<[number, [number, number, number]]> = [
    [0.5, [56, 182, 255]],
    [0.74, [116, 84, 232]],
    [0.97, [208, 74, 228]],
  ]
  if (u <= stops[0]![0]) return [...stops[0]![1]]
  for (let i = 1; i < stops.length; i++) {
    const [u2, c2] = stops[i]!
    if (u <= u2) {
      const [u1, c1] = stops[i - 1]!
      const t = (u - u1) / (u2 - u1)
      return [
        Math.round(c1[0] + (c2[0] - c1[0]) * t),
        Math.round(c1[1] + (c2[1] - c1[1]) * t),
        Math.round(c1[2] + (c2[2] - c1[2]) * t),
      ]
    }
  }
  return [...stops[stops.length - 1]![1]]
}
